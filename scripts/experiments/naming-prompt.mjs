export function namingPrompt(t) {
	return [
		"Ты помогаешь организовать личную базу заметок.",
		"Ниже ключевые слова и названия заметок одной тематической группы.",
		"Придумай короткое название темы (1–4 слова), которое подошло бы для индексной заметки.",
		"Пиши на языке, на котором написано большинство названий. Именительный падеж. Без кавычек.",
		"Не используй общие слова вроде «Заметки», «Разное», «Идеи».",
		'Ответь только JSON: {"name": "...", "alternatives": ["...", "..."]}',
		"",
		"Ключевые слова: " + t.keywords.join(", "),
		"Названия заметок:",
		...t.titles.slice(0, 12).map((x) => "- " + x),
	].join("\n");
}
